// Writes docs/bedrock/reference.md from the Bedrock engine's sources: for each module under lib/bedrock, its header
// comment, then every export with the comment above it and its signature. `node scripts/bedrock-reference.js --check`
// exits non-zero when the file on disk is not what the sources give (test/bedrock/reference.test.js runs it).
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const LIB = path.join(ROOT, 'lib', 'bedrock')
const OUT = path.join(ROOT, 'docs', 'bedrock', 'reference.md')

// The sections, in reading order, and a line on each.
const SECTIONS = [
  ['', 'The physics object and the shared types'],
  ['tick', 'One tick, step by step'],
  ['movement', 'The movement rules'],
  ['world', 'Reading the world'],
  ['math', 'Numbers, boxes and angles'],
  ['network', 'The input packet and the server\'s movement packets']
]

function modulesIn (dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter(e => e.isFile() && e.name.endsWith('.ts'))
    .map(e => path.join(dir, e.name))
    .sort((a, b) => (path.basename(a) === 'index.ts' ? -1 : path.basename(b) === 'index.ts' ? 1 : a.localeCompare(b)))
}

// The comment block ending on the line before `index` (consecutive `//` lines).
function commentAbove (lines, index) {
  const out = []
  for (let i = index - 1; i >= 0 && /^\s*\/\//.test(lines[i]); i--) out.unshift(lines[i].replace(/^\s*\/\/ ?/, ''))
  return out.join(' ').trim()
}

function headerComment (lines) {
  const out = []
  for (const line of lines) {
    if (!/^\/\//.test(line)) break
    out.push(line.replace(/^\/\/ ?/, ''))
  }
  // a blank comment line is a paragraph break
  return out.join('\n').split(/\n\s*\n/).map(p => p.replace(/\n/g, ' ').trim()).filter(Boolean).join('\n\n')
}

// The signature of a function export: the declaration up to its body. The parameter list is the first balanced pair
// of parentheses (a destructured parameter's braces sit inside it); a return type that is an object type is a
// balanced pair of braces; the body is the next brace.
function signature (line) {
  const text = line.replace(/^export\s+(async\s+)?/, '')
  let i = text.indexOf('(')
  for (let depth = 0; i < text.length; i++) {
    if (text[i] === '(') depth++
    else if (text[i] === ')' && --depth === 0) break
  }
  let end = i + 1
  const typed = /^:\s*/.exec(text.slice(end))
  if (!typed) return text.slice(0, end).trim()
  end += typed[0].length
  if (text[end] === '{') {
    for (let depth = 0; end < text.length; end++) {
      if (text[end] === '{') depth++
      else if (text[end] === '}' && --depth === 0) { end++; break }
    }
  }
  const body = text.indexOf(' {', end)
  return text.slice(0, body < 0 ? text.length : body).trim()
}

function describeModule (file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/)
  const rel = path.relative(LIB, file).replace(/\\/g, '/')
  const parts = [`### \`${rel}\``, '']
  const header = headerComment(lines)
  if (header) parts.push(header, '')
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const m = /^export\s+(?:async\s+)?(function|const|class|interface|type)\s+([A-Za-z0-9_$]+)/.exec(line)
    if (!m) continue
    const [, kind, name] = m
    const comment = commentAbove(lines, i)
    const sig = kind === 'function' ? signature(line) : `${kind} ${name}`
    parts.push(`- \`${sig}\`${comment ? ` -- ${comment}` : ''}`)
  }
  const reexports = lines.filter(l => /^export \{/.test(l))
  for (const l of reexports) parts.push(`- re-exports ${l.replace(/^export /, '').replace(/ from .*/, '')}`)
  parts.push('')
  return parts.join('\n')
}

function build () {
  const out = [
    '# Bedrock physics: reference',
    '',
    '<!-- Generated by scripts/bedrock-reference.js from the comments in lib/bedrock; edit those, then run `npm run docs`. -->',
    '',
    'Every module of the engine and what it exports, in the order a tick uses them. See `overview.md` for how they fit',
    'together.',
    ''
  ]
  for (const [dir, title] of SECTIONS) {
    out.push(`## ${dir ? `${dir}/` : 'lib/bedrock'}: ${title}`, '')
    for (const file of modulesIn(path.join(LIB, dir))) out.push(describeModule(file))
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

if (require.main === module) {
  const text = build()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== text) {
      console.error('docs/bedrock/reference.md is out of date: run npm run docs')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(OUT, text)
  }
}

module.exports = { build }
